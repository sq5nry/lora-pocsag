#!/usr/bin/env python3
"""Embed the web console in the firmware: gzip webui/pocsag_console.html into pocsag_fw/web_page.h.

Run from the repository root after changing the console page:  python3 tools/make_web_page.py
"""
import gzip, os, sys

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
src = os.path.join(root, "webui", "pocsag_console.html")
dst = os.path.join(root, "pocsag_fw", "web_page.h")

html = open(src, "rb").read()
gz = gzip.compress(html, compresslevel=9, mtime=0)       # mtime=0: same input, same output

lines = []
for i in range(0, len(gz), 20):
    lines.append("  " + ",".join(f"0x{b:02x}" for b in gz[i:i + 20]) + ",")
out = (
    "// Generated by tools/make_web_page.py from webui/pocsag_console.html - do not edit.\n"
    f"// {len(html)} bytes of HTML, {len(gz)} bytes gzipped.\n"
    "#pragma once\n#include <stdint.h>\n#include <stddef.h>\n\n"
    "static const uint8_t WEB_PAGE_GZ[] = {\n" + "\n".join(lines) + "\n};\n"
    f"static const size_t WEB_PAGE_GZ_LEN = {len(gz)};\n"
)
open(dst, "w", newline="\n").write(out)
print(f"{dst}: {len(html)} -> {len(gz)} bytes")
